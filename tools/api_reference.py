"""Write the API reference in the user guide's appendix, straight from Oread's code.

    python3 tools/api_reference.py          # rewrite the appendix in docs/user-guide.md
    python3 tools/api_reference.py --check  # exit 1 if the appendix is out of date

Only the part between the two "api-reference" markers is generated: every
call, who may make it, what it takes and what it does. The hand-written parts
of the appendix (signing in, errors, the listening ports) sit outside them.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from oread.api import RULES, build_app  # noqa: E402

GUIDE = ROOT / "docs" / "user-guide.md"
START = "<!-- api-reference:start (generated by tools/api_reference.py; don't edit by hand) -->"
END = "<!-- api-reference:end -->"
ORDER = ["public", "account", "status", "resources", "phrases", "clips", "profiles", "devices",
         "settings", "users", "audit", "tokens", "home assistant", "mishearings", "wepwawet", "access", "vault"]
TITLES = {"public": "Signing in (no sign-in needed)", "account": "Your account",
          "home assistant": "Home Assistant (reporting who spoke)",
          "mishearings": "Mishearings (pulled from the house router)", "wepwawet": "The house router's address"}
READING = {"get", "head"}


def who(tag: str, method: str) -> str:
    if tag == "public":
        return "anyone"
    if tag == "account":
        return "anyone signed in"
    read, change = RULES.get(tag, ("administrator", "administrator"))
    return read if method in READING else change


def schema_fields(spec: dict, ref: str) -> str:
    schema = spec["components"]["schemas"][ref.split("/")[-1]]
    required = set(schema.get("required", []))
    parts = []
    for name, prop in schema.get("properties", {}).items():
        kind = prop.get("type")
        if "enum" in prop:
            kind = " \\| ".join(f"`{v}`" for v in prop["enum"])
        elif "anyOf" in prop:
            kinds = []
            for option in prop["anyOf"]:
                if "enum" in option:
                    kinds.append(" \\| ".join(f"`{v}`" for v in option["enum"]))
                elif option.get("type") and option["type"] != "null":
                    kinds.append(option["type"])
            kind = " \\| ".join(kinds) or "any"
        elif kind == "array":
            kind = f"list of {prop.get('items', {}).get('type', 'items')}"
        parts.append(f"`{name}`{'' if name in required else '?'}: {kind}")
    return ", ".join(parts)


def generate() -> str:
    app = build_app(*([None] * 10))
    spec = app.openapi()
    groups: dict[str, list[str]] = {}
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            tag = (op.get("tags") or ["other"])[0]
            params = [f"`{p['name']}`{'' if p.get('required') else '?'}"
                      for p in op.get("parameters", []) if p.get("in") == "query"]
            body = ""
            ref = (op.get("requestBody", {}).get("content", {}).get("application/json", {})
                   .get("schema", {}).get("$ref"))
            if ref:
                body = schema_fields(spec, ref)
            takes = "; ".join(x for x in [("query " + ", ".join(params)) if params else "", body] if x) or "-"
            row = (f"| `{method.upper()} {path}` | {who(tag, method)} | {takes} | "
                   f"{op.get('summary', '').replace('|', '/')} |")
            groups.setdefault(tag, []).append(row)
    out = [START, ""]
    for tag in sorted(groups, key=lambda t: ORDER.index(t) if t in ORDER else len(ORDER)):
        out += [f"#### {TITLES.get(tag, tag.capitalize())}", "",
                "| Call | Who may | Takes | What it does |", "| --- | --- | --- | --- |",
                *groups[tag], ""]
    out.append(END)
    return "\n".join(out)


def main() -> None:
    text = GUIDE.read_text()
    if START not in text or END not in text:
        sys.exit(f"The markers aren't in {GUIDE}")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    new = before + generate() + after
    if "--check" in sys.argv:
        if new != text:
            print("The API reference in docs/user-guide.md is out of date: run tools/api_reference.py")
            sys.exit(1)
        print("API reference up to date")
        return
    GUIDE.write_text(new)
    print("API reference written to docs/user-guide.md")


if __name__ == "__main__":
    main()
