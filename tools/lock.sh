#!/bin/sh
# Regenerate requirements.txt (exact versions of everything, for Docker)
# from requirements.in. Run after editing requirements.in, or to pick up
# newer compatible releases of the ranged libraries.
#
# PYTHON must match the FROM line in the Dockerfile. When moving to a new
# Python, change both, run this, rebuild, then run regress.py and bench.py.
#
# Needs uv: pip install uv
set -e
PYTHON=3.12
cd "$(dirname "$0")/.."
uv pip compile requirements.in --python-version "$PYTHON" \
    --python-platform x86_64-unknown-linux-gnu \
    --no-header --annotate -o requirements.txt
sed -i "1i # Generated by tools/lock.sh from requirements.in for Python $PYTHON. Do not edit by hand." requirements.txt
echo "requirements.txt updated for Python $PYTHON"
